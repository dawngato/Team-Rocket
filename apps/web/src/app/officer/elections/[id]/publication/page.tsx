"use client";

import React, { useEffect, useState } from "react";
import Link from "next/link";
import { useParams } from "next/navigation";
import { motion } from "motion/react";
import { ArrowRight, Send, ShieldCheck, Award, FileCheck2, Key, Clock, AlertCircle, CheckCircle2 } from "lucide-react";
import { StateBadge } from "@/components/StateBadge";
import { apiClient } from "@/lib/api_client";
import type { Election } from "@/lib/types";
import { Breadcrumbs } from "@/components/Breadcrumbs";

export default function OfficerPublicationRequestPage() {
  const params = useParams();
  const electionId = params?.id as string;
  const [election, setElection] = useState<Election | null>(null);
  const [auditorPublicKey, setAuditorPublicKey] = useState("");
  const [auditorSignature, setAuditorSignature] = useState("");
  const [attestation, setAttestation] = useState("");
  const [requested, setRequested] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    if (electionId) {
      void apiClient
        .getElection(electionId, { includeInternal: true })
        .then(setElection)
        .catch((cause) =>
          setError(
            cause instanceof Error
              ? cause.message
              : "Authoritative election record could not be retrieved from the election service."
          )
        );
    }
  }, [electionId]);

  const submit = async () => {
    if (!election) return;
    setBusy(true);
    setError(null);
    try {
      const attestationData = JSON.parse(attestation) as unknown;
      if (!attestationData || typeof attestationData !== "object" || Array.isArray(attestationData)) {
        throw new Error("Attestation payload must be a valid JSON object generated by the independent auditor workflow.");
      }
      const updated = await apiClient.requestPublication(election.id, {
        auditor_public_key: auditorPublicKey.trim(),
        auditor_signature: auditorSignature.trim(),
        attestation_data: attestationData as Record<string, unknown>,
      });
      setElection(updated);
      setRequested(true);
    } catch (cause) {
      setError(
        cause instanceof Error
          ? cause.message
          : "The publication request was rejected by the institutional election service."
      );
    } finally {
      setBusy(false);
    }
  };

  const breadcrumbs = [
    { label: "Workspace", href: "/officer" },
    { label: "Elections", href: "/officer/elections" },
    { label: "Publication Evidence Review" },
  ];

  if (!election) {
    return (
      <main className="mx-auto max-w-5xl px-4 py-12 text-sm text-center text-slate-500" role="status">
        <Clock className="mx-auto mb-2 size-6 animate-pulse text-[#157E92]" />
        {error || "Loading authoritative election record from election service…"}
      </main>
    );
  }

  return (
    <main className="mx-auto max-w-5xl space-y-6 px-4 py-8 sm:px-6 lg:px-8">
      <Breadcrumbs items={breadcrumbs} />

      <header className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-200 pb-6 dark:border-[#1E3352]">
        <div>
          <div className="mb-1 inline-flex items-center gap-1.5 rounded-md bg-[#15805D]/10 px-2.5 py-0.5 text-xs font-semibold text-[#15805D] dark:text-[#34D399]">
            <Send className="size-3.5" aria-hidden="true" />
            Publication Evidence Verification
          </div>
          <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-[#10233F] dark:text-white">
            Official Result Publication Request
          </h1>
          <p className="mt-1 text-xs sm:text-sm text-slate-600 dark:text-slate-400">
            {election.title} · <span className="font-mono text-slate-400">{election.id}</span>
          </p>
        </div>
        <StateBadge state={election.state} size="md" />
      </header>

      {/* Statistics and Telemetry Tiles */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        <motion.div
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.3 }}
          className="p-5 rounded-2xl border border-slate-200 dark:border-[#1E3352] bg-white dark:bg-[#132135] shadow-sm hover:shadow-md transition-shadow"
        >
          <span className="text-[11px] font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 block">
            Election Consensus State
          </span>
          <div className="mt-2 text-2xl font-extrabold font-mono text-[#10233F] dark:text-white">
            {election.state}
          </div>
          <span className="text-xs text-slate-500 dark:text-slate-400 mt-1 block">
            Authoritative lifecycle stage
          </span>
        </motion.div>

        <motion.div
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.3, delay: 0.05 }}
          className="p-5 rounded-2xl border border-slate-200 dark:border-[#1E3352] bg-white dark:bg-[#132135] shadow-sm hover:shadow-md transition-shadow"
        >
          <span className="text-[11px] font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 block">
            Auditor Attestation
          </span>
          <div className="mt-2 text-base font-bold text-[#15805D] dark:text-[#34D399] flex items-center gap-1.5">
            <FileCheck2 className="size-4" />
            <span>Cryptographic Proof Gate</span>
          </div>
          <span className="text-xs text-slate-500 dark:text-slate-400 mt-1 block">
            Requires signed auditor verification
          </span>
        </motion.div>

        <motion.div
          initial={{ opacity: 0, y: 10 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ duration: 0.3, delay: 0.1 }}
          className="p-5 rounded-2xl border border-slate-200 dark:border-[#1E3352] bg-white dark:bg-[#132135] shadow-sm hover:shadow-md transition-shadow"
        >
          <span className="text-[11px] font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 block">
            Dual Sign-Off Gate
          </span>
          <div className="mt-2 text-base font-bold text-[#157E92] dark:text-[#38BDF8] flex items-center gap-1.5">
            <span className="relative flex h-2 w-2">
              <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-[#157E92] opacity-75" />
              <span className="relative inline-flex rounded-full h-2 w-2 bg-[#157E92]" />
            </span>
            <span>Witness &amp; Anchor Enforced</span>
          </div>
          <span className="text-xs text-slate-500 dark:text-slate-400 mt-1 block">
            Publication occurs only upon gate passage
          </span>
        </motion.div>
      </div>

      {error && (
        <div
          className="rounded-xl border border-[#C23C45]/30 bg-[#C23C45]/10 p-4 text-xs sm:text-sm font-medium text-[#8B2630] dark:text-[#FCA5A5]"
          role="alert"
        >
          {error}
        </div>
      )}

      {requested ? (
        <div
          className="space-y-2 rounded-2xl border border-[#15805D]/30 bg-[#15805D]/10 p-6 text-sm text-[#0F5B43] dark:text-[#86EFAC]"
          role="status"
        >
          <div className="flex items-center gap-2 font-bold text-base">
            <CheckCircle2 className="size-5" />
            <span>Publication request accepted by the authoritative election service.</span>
          </div>
          <p className="text-xs sm:text-sm leading-relaxed">
            The authoritative election state has transitioned to <strong>{election.state}</strong>. Finalized tally summaries and candidate outcome receipts remain unreleased to the public portal until the complete witness, anchor, auditor, and tally gates achieve full verification.
          </p>
        </div>
      ) : (
        <section className="space-y-5 rounded-2xl border border-slate-200 bg-white p-6 shadow-sm dark:border-[#1E3352] dark:bg-[#132135]">
          <div className="space-y-1">
            <h2 className="text-base font-bold text-[#10233F] dark:text-white">
              Submit Independent Auditor Verification Package
            </h2>
            <p className="text-xs leading-relaxed text-slate-600 dark:text-slate-400">
              Provide the cryptographically signed attestation package produced by the independently operated auditor. The platform never generates keys or signs attestations locally; the backend cryptographically verifies the signature before authorizing result publication.
            </p>
          </div>

          <div className="space-y-4">
            <div className="space-y-1.5">
              <label htmlFor="auditor-pubkey" className="block text-xs font-semibold text-slate-700 dark:text-slate-300">
                Auditor Public Key (Hex / Base64)
              </label>
              <input
                id="auditor-pubkey"
                required
                value={auditorPublicKey}
                onChange={(event) => setAuditorPublicKey(event.target.value)}
                placeholder="ed25519:…"
                className="min-h-11 w-full rounded-xl border border-slate-300 bg-transparent px-3.5 font-mono text-xs sm:text-sm text-slate-900 outline-none transition focus:border-[#157E92] focus:ring-2 focus:ring-[#157E92]/20 dark:border-[#1E3352] dark:text-white"
              />
            </div>

            <div className="space-y-1.5">
              <label htmlFor="auditor-sig" className="block text-xs font-semibold text-slate-700 dark:text-slate-300">
                Auditor Digital Signature
              </label>
              <input
                id="auditor-sig"
                required
                value={auditorSignature}
                onChange={(event) => setAuditorSignature(event.target.value)}
                placeholder="sig:…"
                className="min-h-11 w-full rounded-xl border border-slate-300 bg-transparent px-3.5 font-mono text-xs sm:text-sm text-slate-900 outline-none transition focus:border-[#157E92] focus:ring-2 focus:ring-[#157E92]/20 dark:border-[#1E3352] dark:text-white"
              />
            </div>

            <div className="space-y-1.5">
              <label htmlFor="attestation-json" className="block text-xs font-semibold text-slate-700 dark:text-slate-300">
                Signed Attestation Document (JSON)
              </label>
              <textarea
                id="attestation-json"
                required
                rows={8}
                value={attestation}
                onChange={(event) => setAttestation(event.target.value)}
                placeholder='{"election_id": "...", "merkle_root": "...", "timestamp": ...}'
                className="w-full rounded-xl border border-slate-300 bg-transparent p-3.5 font-mono text-xs text-slate-900 outline-none transition focus:border-[#157E92] focus:ring-2 focus:ring-[#157E92]/20 dark:border-[#1E3352] dark:text-white"
              />
            </div>

            <button
              type="button"
              disabled={busy}
              onClick={() => void submit()}
              className="inline-flex min-h-11 items-center gap-2 rounded-xl bg-[#157E92] hover:bg-[#0E6273] px-5 text-sm font-bold text-white shadow-sm transition-colors disabled:opacity-50"
            >
              <Send className="size-4" aria-hidden="true" />
              <span>{busy ? "Submitting for Verification…" : "Submit Signed Publication Package"}</span>
            </button>
          </div>
        </section>
      )}

      <div className="pt-2">
        <Link
          href={`/audit?election=${encodeURIComponent(election.id)}`}
          className="inline-flex min-h-11 items-center gap-2 text-xs sm:text-sm font-bold text-[#157E92] dark:text-[#38BDF8] hover:underline"
        >
          <ShieldCheck className="size-4" />
          <span>Inspect Complete Cryptographic Audit Evidence</span>
          <ArrowRight className="size-4" aria-hidden="true" />
        </Link>
      </div>
    </main>
  );
}
